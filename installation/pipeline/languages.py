def _fold(s):
    """Accent- and case-insensitive key. Lets 'Proven\u00e7al' match the ASCII
    alias 'Provencal' without needing both spellings written out, which the
    corpora mix freely."""
    d = unicodedata.normalize("NFD", s)
    return u"".join(c for c in d if not unicodedata.combining(c)).lower().strip()


_FOLDED = None


def resolve(tag):
    """Return (code, name, current, depth, script) for a raw corpus tag."""
    global _FOLDED
    tag = tag.strip()
    code = ALIAS.get(tag, tag)
    if code not in LANG:
        code_l = code.lower()
        code = ALIAS.get(code_l, code_l)
    if code not in LANG:
        if _FOLDED is None:
            _FOLDED = {}
            for k, v in ALIAS.items():
                _FOLDED.setdefault(_fold(k), v)
            for k in LANG:
                _FOLDED.setdefault(_fold(k), k)
        code = _FOLDED.get(_fold(tag), code)
    if code in LANG:
        name, current, depth, script = LANG[code]
        return code, name, current, depth, script
    return None


