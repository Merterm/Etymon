"""
Etymon language metadata.

The 2018 client carried a ~130-case `convertISO` switch statement inside
main.js. The corpora actually contain ~600 distinct language tags, including
Turkish-language labels left over from the Nisanyan scrape ("Eski Turkce").
This module is that switch statement grown up: for every tag we care about it
records an English name, a "current" (the visual/genealogical grouping the
installation colours by), an era depth, and a script.

`depth` is the installation's vertical axis. 0 is the ocean surface (living
languages), 4 is the abyssal floor (reconstructed proto-forms). Constructed
languages are pinned to the surface with depth 0 and are drawn hollow: they
are inventions, they have no ancestry to sink into.

  0  living / modern
  1  early modern, recently historical
  2  medieval
  3  ancient, classical, attested-and-dead
  4  proto, reconstructed, unattestable

`current` values are declared in CURRENTS below. Ten currents carry a hue of
their own; everything else is "distant" and is drawn as pearl-white flecks,
which is honest about the four source corpora's actual coverage (Indo-European,
Turkic and Semitic) rather than pretending to a uniform world map.
"""

